package com.example.queuerunner.game.main

// 박스가 장애물과 충돌했을 때 어떤 효과가 발동할지를 나타내는 enum.
//
// 충돌 검사 흐름:
//   1) 커맨드 입력으로 점프(또는 슬로우 이동) 가 시작되기 직전,
//      착지 예정 virtualX 를 계산해 그 자리에 있는 장애물을 미리 찾는다.
//   2) 장애물이 있어도 일단 이동은 그대로 수행한다. (이동 중 새 입력은 받지 않음)
//   3) 박스가 실제로 착지하는 순간, 미리 찾아둔 장애물의 HitEffect 가 발동된다.
//
// 즉 "검사는 점프 시작 전" 이고 "효과는 착지 후" 라는 점이 중요하다.
// 점프 도중에는 어떤 평가도 일어나지 않으므로, 키 큰 장애물 위로 X+X 점프해서 넘는 경우도
// 자연스럽게 무충돌이 된다.
//
// SLOWDOWN
//   1칸 장애물(쓰레기봉투/음식물통/고양이) 과 2칸 웅덩이에 적용.
//   착지 후 박스가 입력을 받지 않는 슬로우 모드로 진입해
//   y 고정인 채 x 만 1칸(BLOCK_SIZE) 천천히 미끄러진다.
//   슬로우 이동 직전에도 똑같이 "다음 착지 예정 X 검사" 가 한 번 더 일어나기 때문에,
//   2칸 웅덩이의 두 번째 칸도 같은 방식으로 슬로우가 한 번 더 발동된다.
//   슬로우가 끝났을 때 미리 검사한 장애물이 없다면 그때 다시 입력을 받기 시작한다.
//
// GAME_OVER
//   2칸 맨홀과 3칸 자동차에 적용.
//   박스가 빠지거나 찌그러져 더 이상 움직일 수 없는 상태가 되었음을 의미한다.
//   MainScene 이 이 효과를 감지하면 Janitor.isCaught 와 동일한 경로로 GameOverScene 을 push 한다.
//
// 추후 NONE 같은 무해 효과(행인 등) 가 필요해지면 여기에 추가한다.
enum class HitEffect {
    SLOWDOWN,
    GAME_OVER,
}